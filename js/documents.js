/* GovShield – Official Documents
   Every application becomes a document. It can be downloaded once it is Approved. */

let documentList = [];

function downloadCounterKey() {
    return "govshield_downloads_" + (currentGovShieldUser ? currentGovShieldUser.nid : "guest");
}

function getDownloadCount() {
    try { return parseInt(localStorage.getItem(downloadCounterKey()) || "0", 10) || 0; } catch (e) { return 0; }
}

function addDownloadCount() {
    try { localStorage.setItem(downloadCounterKey(), String(getDownloadCount() + 1)); } catch (e) { /* storage blocked */ }
}

async function loadDocuments() {
    const body = document.getElementById("docBody");
    try {
        const apps = await api.listApplications();
        documentList = apps.map(function (a) {
            return { name: a.service, reference: a.id, date: a.date, holder: a.name, nid: a.nid,
                     available: a.status === "Approved", status: a.status };
        });
        renderDocuments();
    } catch (error) {
        body.innerHTML = emptyRow(5, error.message);
    }
}

function renderDocuments() {
    const search = document.getElementById("docSearch").value.trim().toLowerCase();
    const available = documentList.filter(function (d) { return d.available; });
    document.getElementById("docTotal").textContent = documentList.length;
    document.getElementById("docAvailable").textContent = available.length;
    document.getElementById("docDownloads").textContent = getDownloadCount();
    document.getElementById("docLatest").textContent = available.length
        ? available.map(function (d) { return d.date; }).sort().pop() : "-";

    const rows = documentList.filter(function (d) {
        return !search || (d.name + " " + d.reference).toLowerCase().includes(search);
    });
    document.getElementById("docBody").innerHTML = rows.length ? rows.map(function (d) {
        const action = d.available
            ? '<button class="btn btn-success btn-sm" data-doc="' + escapeHtml(d.reference) + '">Download</button>'
            : '<span style="color:#64748b;font-size:13px;">Available after approval</span>';
        return "<tr><td>" + escapeHtml(d.name) + "</td><td>" + escapeHtml(d.reference) + "</td><td>" +
            escapeHtml(d.date) + "</td><td>" + statusBadge(d.available ? "Available" : d.status) +
            "</td><td>" + action + "</td></tr>";
    }).join("") : emptyRow(5, documentList.length ? "No documents match your search." : "No documents yet. Apply for a service first.");
}

/* Builds a printable HTML certificate and saves it to the computer. */
function downloadDocument(reference) {
    const d = documentList.find(function (x) { return x.reference === reference && x.available; });
    if (!d) { alert("This document is not available yet."); return; }

    const html = '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>' + escapeHtml(d.name) + " - " + escapeHtml(d.reference) + "</title>" +
        "<style>body{font-family:Arial,sans-serif;margin:0;padding:40px;color:#0f172a}" +
        ".page{max-width:720px;margin:auto;border:3px double #0f3d5e;padding:40px;text-align:center}" +
        "h1{color:#0f3d5e;margin:0 0 6px}h2{margin:24px 0}table{margin:24px auto;text-align:left;border-collapse:collapse}" +
        "td{padding:8px 16px;border-bottom:1px solid #e2e8f0}.note{margin-top:30px;font-size:12px;color:#64748b}</style></head><body>" +
        '<div class="page"><h1>GovShield</h1><div>Digital Government Services Portal</div>' +
        "<h2>" + escapeHtml(d.name) + "</h2><table>" +
        "<tr><td><strong>Reference</strong></td><td>" + escapeHtml(d.reference) + "</td></tr>" +
        "<tr><td><strong>Issued to</strong></td><td>" + escapeHtml(d.holder) + "</td></tr>" +
        "<tr><td><strong>NID</strong></td><td>" + escapeHtml(d.nid) + "</td></tr>" +
        "<tr><td><strong>Application date</strong></td><td>" + escapeHtml(d.date) + "</td></tr>" +
        "<tr><td><strong>Status</strong></td><td>Approved</td></tr></table>" +
        '<div class="note">DEMO DOCUMENT - generated by a classroom project with fictional data. Not an official government document.</div></div></body></html>';

    const blob = new Blob([html], { type: "text/html" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = d.reference + "_" + d.name.replace(/[^A-Za-z0-9]+/g, "_") + ".html";
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(function () { URL.revokeObjectURL(url); }, 1000);

    addDownloadCount();
    renderDocuments();
}

onPageShow("documents", loadDocuments);

document.addEventListener("DOMContentLoaded", function () {
    document.getElementById("docSearch").addEventListener("input", renderDocuments);
    document.getElementById("docBody").addEventListener("click", function (event) {
        const button = event.target.closest("[data-doc]");
        if (button) downloadDocument(button.dataset.doc);
    });
});
